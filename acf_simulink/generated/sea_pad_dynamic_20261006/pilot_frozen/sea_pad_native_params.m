function p=sea_pad_native_params(contractFile,overrides)
% Prepare constants and equilibrium; no dynamic plant solver is used here.
c=jsondecode(fileread(contractFile));if nargin<2,overrides=struct;end
p=struct('dt',c.numerics.base_step_s,'controlStep',1/c.acquisition.controller_rate_Hz, ...
 'stopTime',c.surface.duration_s,'mA',c.mechanics.mA_kg,'mB',c.mechanics.mB_kg, ...
 'mS',1.4,'gAxis',c.mechanics.gravity_m_s2*cos(pi/4),'Fref',20, ...
 'kUpper',c.mechanics.upper_stiffness_N_m,'kCell',c.mechanics.cell_stiffness_N_m, ...
 'sea',0,'mNut',c.mechanics.nut_translation_mass_kg,'kSea',5000,'cSea',0,'preload',0, ...
 'ell',.01/(2*pi),'Jtotal',c.screw_motor.rotor_inertia_kg_m2+c.screw_motor.assumed_screw_coupler_inertia_kg_m2, ...
 'Kf',c.coil.Kf_N_A,'Kt',c.screw_motor.Kt_Nm_A,'Ke',c.screw_motor.Ke_V_s_rad, ...
 'R',c.coil.R_hot_ohm,'L',c.coil.L_H,'Imax',c.coil.peak_current_A, ...
 'Vmax',c.coil.usable_voltage_V,'currentTau',c.coil.current_response_s, ...
 'guideCoulomb',c.mechanics.guide_coulomb_N,'guideViscous',c.mechanics.guide_viscous_N_s_m, ...
 'guideSmooth',c.mechanics.guide_smoothing_m_s, ...
 'shaftCoulomb',c.screw_motor.shaft_coulomb_Nm,'shaftViscous',c.screw_motor.shaft_viscous_Nm_s_rad, ...
 'shaftSmooth',c.screw_motor.shaft_smoothing_rad_s, ...
 'kPad',50000,'cPad',80,'padDiameter',0,'stripCount',c.pad.strips, ...
 'bumpTime',c.surface.point_bump_start_s,'bumpHeight',c.surface.height_m, ...
 'bumpWidth',c.surface.width_m,'scanSpeed',c.surface.scan_speed_m_s, ...
 'toolTravelLimit',c.mechanics.flange_u_hard_limit_m,'nutTravelLimit',c.mechanics.nut_q_hard_limit_m, ...
 'springTravelLimit',c.mechanics.sea_signed_deflection_limit_m,'padCompressionLimit',.0025,'enableStops',1);
names=fieldnames(overrides);for j=1:numel(names),p.(names{j})=overrides.(names{j});end
if p.sea
 p.R=c.screw_motor.R_hot_ohm;p.L=c.screw_motor.L_H;p.Imax=c.screw_motor.peak_current_A;
 p.Vmax=c.screw_motor.usable_voltage_V;p.currentTau=c.screw_motor.current_response_s;
end
% Explicit case values override catalogue defaults (e.g. refinement or stress).
for j=1:numel(names),p.(names{j})=overrides.(names{j});end
if p.padDiameter==0
 p.offsets=0;p.weights=1;
else
 edges=linspace(-p.padDiameter/2,p.padDiameter/2,p.stripCount+1);
 p.offsets=((edges(1:end-1)+edges(2:end))/2)';
 radius=p.padDiameter/2;
 primitive=edges.*sqrt(max(0,radius^2-edges.^2))+radius^2*asin(edges/radius);
 p.weights=diff(primitive)/(pi*radius^2);
end
p.centerWeight=zeros(1,numel(p.offsets));p.centerWeight(ceil(numel(p.offsets)/2))=1;
p.rigidPoint=p.kPad<=0;
F=p.Fref;g=p.gAxis;L0=F-p.mS*g;Fa0=F-(p.mB+p.mS)*g;
if p.rigidPoint,zS0=0;p.padCompressionLimit=inf;else,zS0=-F/p.kPad;end
zB0=zS0-L0/p.kCell;
if p.sea,zA0=(Fa0-(p.mA+p.mNut)*g)/p.kUpper;i0=(Fa0-p.mNut*g)*p.ell/p.Kt;
else,zA0=(Fa0-p.mA*g)/p.kUpper;i0=Fa0/p.Kf;end
if p.sea,q0=zA0-zB0+(Fa0-p.preload)/p.kSea;else,q0=0;end
p.initial=[zA0 0 zB0 0 zS0 0 q0 0 i0];
p.massInverse=inv([p.mA+p.mNut,-p.mNut;-p.mNut,p.mNut+p.Jtotal/p.ell^2]);
end
