function p=sea_pad_native_from_engine(contractFile,c)
% Translate an explicit fast-engine case into the independently built plant.
o=struct('dt',c.dt,'controlStep',1/c.control_rate,'stopTime',c.duration, ...
 'mA',c.mass_a,'mB',c.mass_b,'mS',c.mass_s,'gAxis',c.gravity*cos(c.angle_deg*pi/180), ...
 'Fref',c.force_target,'kUpper',c.upper_k,'kCell',c.cell_k,'sea',c.actuator, ...
 'mNut',c.nut_mass,'kSea',c.sea_k,'cSea',c.sea_c,'ell',c.lead/(2*pi), ...
 'Jtotal',c.rotor_inertia,'R',c.resistance,'L',c.inductance,'Imax',c.current_limit, ...
 'Vmax',c.voltage_limit,'currentTau',c.current_response, ...
 'guideCoulomb',c.guide_coulomb,'guideViscous',c.guide_viscous,'guideSmooth',c.guide_eps, ...
 'shaftCoulomb',c.shaft_coulomb,'shaftViscous',c.shaft_viscous,'shaftSmooth',c.shaft_eps, ...
 'kPad',c.pad_k,'cPad',c.pad_c,'padDiameter',c.pad_diameter,'stripCount',c.pad_points, ...
 'bumpTime',c.bump_start,'bumpHeight',c.bump_height,'bumpWidth',c.bump_width,'scanSpeed',c.scan_speed, ...
 'toolTravelLimit',c.tool_travel_limit,'nutTravelLimit',c.nut_travel_limit, ...
 'springTravelLimit',c.spring_deflection_limit,'padCompressionLimit',c.pad_compression_limit);
if c.pad_compression_limit<=0,o.padCompressionLimit=inf;end
if c.actuator==0,o.Kf=c.force_constant;else,o.Kt=c.force_constant;o.Ke=c.force_constant;end
p=sea_pad_native_params(contractFile,o);
end
