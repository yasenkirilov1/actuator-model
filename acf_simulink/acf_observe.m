function y = acf_observe(x,robot,surface,p)
%ACF_OBSERVE No direct feedthrough from the NEW actuator command.
% Acceleration/electrical diagnostics use the command held over the last step.
[~,a]=acf_plant_rhs(x(1:8),x(13),robot,surface,x(9)>0.5,p);
d=p.d;
if x(9)>0.5, s=surface(1); vs=surface(2); else, s=x(5); vs=x(6); end
y=[max(0,a(1));p.mechanics.midTravel+x(3);x(4);a(4); ...
    x(1)+d.beta*x(3);x(1)-d.alpha*x(3);s; ...
    x(2)+d.beta*x(4);x(2)-d.alpha*x(4);vs; ...
    a(5);a(6);a(2);a(9);a(10);a(11);a(12); ...
    x(9);x(10);x(11);x(12);a(14);a(15);a(7);a(8)];
end
