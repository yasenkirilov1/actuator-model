function run_adc_followups_20261002(project)
% Native finite sensing robustness comparisons. Every cohort owns its output.
source=fullfile(project,'acf_simulink','validation','adc_acquisition_trial_20261002');
root=fullfile(project,'acf_simulink','validation');
common=struct('selectedCutoff_Hz',8000,'useFastRestart',false,'seeds',[7 29]);
jobs={...
 'adc_sinc_long15000_20261002','calibrated_long',struct('selectedRate_Hz',15000);...
 'adc_sinc_noise2x_20261002','noise_latency',struct('adcNoiseMultiplier',2);...
 'adc_sinc_noise_corr200us_20261002','noise_latency',struct('adcNoiseCorrelationTime_s',200e-6);...
 'adc_sinc_acc_skew20us_20261002','noise_latency',struct('accelerationExtraDelay_s',20e-6);...
 'adc_sinc_acc_skew50us_20261002','noise_latency',struct('accelerationExtraDelay_s',50e-6);...
 'adc_sinc_refine_20261002','refinement',struct('solverStep_s',1/600000);...
 'adc_sinc_alias_probe_20261002','alias_probe',struct('solverStep_s',1/1200000,'seeds',0,'keepAllTraces',true);...
 'adc_sar_alias_probe_20261002','alias_probe',struct('selectedConverter','sar','selectedRate_Hz',20000,'solverStep_s',1/1200000,'seeds',0,'keepAllTraces',true)};
for k=1:size(jobs,1)
 opts=common;override=jobs{k,3};
 for name=fieldnames(override)',opts.(name{1})=override.(name{1});end
 qualify_adc_acquisition_20261002(source,fullfile(root,jobs{k,1}),jobs{k,2},opts);
end
end
