function merge_screw_preparation(file,donorFile)
body=fileread(file);donor=fileread(donorFile);
old="assert(~(m.lowerRigid || m.upperRigid) || strcmp(p.actuator.kind,'voice_coil'), ...";
new="assert(~(m.lowerRigid || m.upperRigid) || strcmp(p.actuator.kind,'voice_coil') || (strcmp(p.actuator.kind,'leadscrew') && m.upperRigid), ...";
body=replace_once(body,old,new);
old='J = p.screw.rotorInertia+p.d.mu*p.d.ell^2;';
new='p.d.screwMovingMass=p.d.mu;if m.upperRigid,p.d.screwMovingMass=m.mB;end;J = p.screw.rotorInertia+p.d.screwMovingMass*p.d.ell^2;';
body=replace_once(body,old,new);
start=strfind(donor,"if isfield(p.screw,'currentForceKp')");assert(numel(start)==1);
last=strfind(donor(start:end),"if isfield(p,'inertial')");assert(~isempty(last));
extension=donor(start:start+last(1)-2);
body=replace_once(body,'p.d.coilControl=coil_controller(p);',['p.d.coilControl=coil_controller(p);' newline extension]);
fid=fopen(file,'w');assert(fid>0);cleanup=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',body);
end
function replace_page(target,donor,name)
old=[target '/' name];source=[donor '/' name];pos=get_param(old,'Position');ports=get_param(old,'PortHandles');
inputs=[];for j=1:numel(ports.Inport),line=get_param(ports.Inport(j),'Line');if line==-1,inputs(j)=-1;else,inputs(j)=get_param(line,'SrcPortHandle');delete_line(target,inputs(j),ports.Inport(j));end,end
outputs=cell(1,numel(ports.Outport));
for j=1:numel(ports.Outport),line=get_param(ports.Outport(j),'Line');if line~=-1,outputs{j}=get_param(line,'DstPortHandle');delete_line(line);end,end
delete_block(old);add_block(source,old,'Position',pos);replacement=get_param(old,'PortHandles');
for j=1:numel(inputs),if inputs(j)~=-1,add_line(target,inputs(j),replacement.Inport(j),'autorouting','on');end,end
for j=1:numel(outputs),for k=1:numel(outputs{j}),if outputs{j}(k)~=-1,add_line(target,replacement.Outport(j),outputs{j}(k),'autorouting','on');end,end,end
end
function add_native_control_clock(mdl)
ports=get_param([mdl '/Control log'],'PortHandles');line=get_param(ports.Inport(1),'Line');src=get_param(line,'SrcPortHandle');delete_line(mdl,src,ports.Inport(1));
add_block('simulink/Discrete/Zero-Order Hold',[mdl '/Native control history clock'],'SampleTime','p.sim.step','Position',[1570 1220 1840 1275]);
clock=get_param([mdl '/Native control history clock'],'PortHandles');add_line(mdl,src,clock.Inport(1),'autorouting','on');add_line(mdl,clock.Outport(1),ports.Inport(1),'autorouting','on');
end

function fix_gap_acceleration(mdl)
% Diagnostics use the actual body accelerations for every actuator/topology.
% The screw extension's boundary load is not the coil's reduced-mass load.
page=[mdl '/Actuator and RABS mechanics/Measurements and safety'];
destination=[page '/Send gap_acceleration_m_s2'];ports=get_param(destination,'PortHandles');
delete_line(get_param(ports.Inport(1),'Line'));
add_block('simulink/Signal Routing/From',[page '/A acceleration for physical gap'], ...
    'GotoTag','body_acceleration_1','Position',[40 780 255 810]);
add_block('simulink/Signal Routing/From',[page '/B acceleration for physical gap'], ...
    'GotoTag','body_acceleration_2','Position',[40 875 255 905]);
add_block('simulink/Math Operations/Sum',[page '/Physical A minus B acceleration'], ...
    'Inputs','+-','IconShape','rectangular','Position',[360 795 390 895]);
add_line(page,'A acceleration for physical gap/1','Physical A minus B acceleration/1','autorouting','on');
add_line(page,'B acceleration for physical gap/1','Physical A minus B acceleration/2','autorouting','on');
add_line(page,'Physical A minus B acceleration/1','Send gap_acceleration_m_s2/1','autorouting','on');
end

