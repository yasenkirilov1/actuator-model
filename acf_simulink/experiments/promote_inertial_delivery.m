function result=audit_native(mdl)
all=find_system(mdl,'MatchFilter',@Simulink.match.allVariants,'LookUnderMasks','all','FollowLinks','on','Type','block');
references={};
for j=1:numel(all)
    params=get_param(all{j},'DialogParameters');if ~isstruct(params),continue;end
    names=fieldnames(params);
    for k=1:numel(names)
        try,value=get_param(all{j},names{k});catch,continue;end
        if (ischar(value)||isstring(value))&&contains(string(value),'p.d.coilControl')
            references{end+1}=all{j}; %#ok<AGROW>
        end
    end
end
result=struct('blockCount',numel(all),'obsoleteReferences',{references}, ...
    'sFunctionBlocks',{find_system(mdl,'MatchFilter',@Simulink.match.allVariants,'LookUnderMasks','all','BlockType','S-Function')}, ...
    'matlabFunctionBlocks',{find_system(mdl,'MatchFilter',@Simulink.match.allVariants,'LookUnderMasks','all','SFBlockType','MATLAB Function')});
end

function value=replace_once(value,old,new)
assert(numel(strfind(value,char(old)))==1,'Preparation source marker changed: %s',old);
value=strrep(value,char(old),char(new));
end
function hash=sha256(file)
quote=char(39);escaped=[quote,strrep(file,quote,[quote,char(34),quote,char(34),quote]),quote];
[code,output]=system(['sha256sum -- ' escaped]);assert(code==0,'Cannot hash private source.');hash=strtok(output);
end
