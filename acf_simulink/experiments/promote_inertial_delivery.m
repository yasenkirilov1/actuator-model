function apply_feedforward_selector(mdl)
for item={'Coil PI and PID','Screw normal PI and PID'}
    page=[mdl '/Force controller/' item{1}];blocks=find_system(page,'LookUnderMasks','all','FollowLinks','on','BlockType','Gain');
    for j=1:numel(blocks)
        gain=get_param(blocks{j},'Gain');
        if contains(gain,'accelerationFeedforwardScale')||contains(gain,'guideFrictionFeedforwardScale')|| ...
                contains(gain,'geometryFeedforwardScale')||contains(gain,'lowerLoadInverse.enabled')||contains(gain,'screwLowerLoadInverse.enabled')
            set_param(blocks{j},'Gain',['(' gain ')*double(p.force.feedforwardEnabled)']);
        end
    end
end
selector=[mdl '/Force controller selection'];mask=Simulink.Mask.get(selector);
parameter=mask.getParameter('ControllerChoice');parameter.TypeOptions={'Feedforward PI','PI','PID'};parameter.Prompt='Normal force controller';
if ~isempty(mask.getParameter('AccelerationFeedforward')),mask.removeParameter('AccelerationFeedforward');end
mask.Description='Choose Feedforward PI for the tested controller, or compare PI/PID using the same reconstructed workpiece normal force. Gains live in p.inertial for the coil and p.screw for the leadscrew.';
mask.Display="disp(sprintf('Normal force control\\n%s',get_param(gcb,'ControllerChoice')));";
end
