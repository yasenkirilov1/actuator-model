function result=workspace_variables(mw)
v=mw.whos;result=struct;for j=1:numel(v),result.(v(j).name)=getVariable(mw,v(j).name);end
end
function result=edges(mdl)
result={};lines=find_system(mdl,'LookUnderMasks','all','FollowLinks','off','IncludeCommented','on', ...
 'MatchFilter',@Simulink.match.allVariants,'FindAll','on','Type','line');
for j=1:numel(lines)
 try,src=get_param(lines(j),'SrcPortHandle');dst=get_param(lines(j),'DstPortHandle');catch,continue,end
 if src<0,continue,end
 srcParent=get_param(src,'Parent');srcSID=Simulink.ID.getSID(srcParent);srcNumber=get_param(src,'PortNumber');
 for k=1:numel(dst)
  if dst(k)<0,continue,end
  dstParent=get_param(dst(k),'Parent');dstSID=Simulink.ID.getSID(dstParent);dstNumber=get_param(dst(k),'PortNumber');
  result{end+1}=sprintf('%s:%d>%s:%d',srcSID,srcNumber,dstSID,dstNumber); %#ok<AGROW>
 end
end
result=sort(unique(result));
end
function d=sample_rows(ts,width)
n=numel(ts.Time);d=ts.Data;if size(d,1)~=n,assert(size(d,ndims(d))==n);d=permute(d,[ndims(d),1:ndims(d)-1]);end;d=reshape(d,n,width);
end
function finish(mdl,storage,record,sdi)
try,close_system(mdl,0);catch,end
try,Simulink.sdi.clear;Simulink.sdi.setStorageLocation(storage);Simulink.sdi.setRecordData(record);catch,end
if isfile(fullfile(sdi,'owned_fixed_publish')),try,rmdir(sdi,'s');catch,end,end
end
function write_json(file,value),fid=fopen(file,'w');assert(fid>=0);fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));fclose(fid);end
function hash=sha256(path)
fid=fopen(path,'rb');assert(fid>=0);cleanup=onCleanup(@()fclose(fid));digest=java.security.MessageDigest.getInstance('SHA-256'); %#ok<NASGU>
while ~feof(fid),bytes=fread(fid,1024*1024,'*uint8');digest.update(typecast(bytes,'int8'));end
hash=lower(reshape(dec2hex(typecast(digest.digest(),'uint8'),2)',1,[]));
end
