function report=publish_runnable_fixed_model_v8(acceptedFolder,acceptanceFolder,targetFolder,checkFolder)
% Publish only a new versioned folder; the public reference stays untouched.
assert(~usejava('desktop'));maxNumCompThreads(2);assert(~isfolder(targetFolder)&&~isfolder(checkFolder));
mkdir(targetFolder);mkdir(checkFolder);copyfile(fullfile(acceptedFolder,'helpers'),fullfile(targetFolder,'helpers'));
mdl='acf_force_control_fixed_upper_20261005';modelFile=fullfile(targetFolder,[mdl '.slx']);
copyfile(fullfile(acceptedFolder,[mdl '.slx']),modelFile);
oldStorage=Simulink.sdi.getStorageLocation;oldRecord=Simulink.sdi.getRecordData;
sdi=tempname('/dev/shm');mkdir(sdi);fid=fopen(fullfile(sdi,'owned_fixed_publish'),'w');fprintf(fid,'Owned versioned model publish check.\n');fclose(fid);
Simulink.sdi.setStorageLocation(sdi);Simulink.sdi.setRecordData(true);
Simulink.fileGenControl('set','CacheFolder',fullfile(checkFolder,'cache'),'CodeGenFolder',fullfile(checkFolder,'code'),'createDir',true);
addpath(fullfile(targetFolder,'helpers'),'-begin');load_system(modelFile);
cleanup=onCleanup(@()finish(mdl,oldStorage,oldRecord,sdi)); %#ok<NASGU>
mw=get_param(mdl,'ModelWorkspace');originalVariables=workspace_variables(mw);beforeEdges=edges(mdl);

% This existing diagnostic scope now shows workpiece-normal error. Its From
% block is used only by the scope's true-error branch, never by the controller.
scopeSource=[mdl '/Receive true_contact_force_N 5'];
set_param(scopeSource,'GotoTag','normal_contact_N','Name','Receive workpiece normal force');
set_param([mdl '/True force error'],'Name','True normal force error');
scope=[mdl '/Force tolerance scope'];set_param(scope,'Commented','off','Name','Normal force error scope');
configuration=get_param([mdl '/Normal force error scope'],'ScopeConfiguration');configuration.OpenAtSimulationStart=false;

% Strip only unconnected leaf wire segments, retaining every connected edge.
wireCount=0;
for pass=1:5
 changed=false;lines=find_system(mdl,'LookUnderMasks','all','FollowLinks','off','IncludeCommented','on', ...
  'MatchFilter',@Simulink.match.allVariants,'FindAll','on','Type','line');
 for j=1:numel(lines)
  try,dst=get_param(lines(j),'DstPortHandle');if isempty(dst)||all(dst<0),delete_line(lines(j));wireCount=wireCount+1;changed=true;end;catch,end
 end
 if ~changed,break,end
end
assert(isequal(beforeEdges,edges(mdl)),'Wire cleanup changed a connected port edge.');
blocks=find_system(mdl,'LookUnderMasks','all','FollowLinks','off','IncludeCommented','on', ...
 'MatchFilter',@Simulink.match.allVariants,'Type','block');
for j=1:numel(blocks)
 parameters=get_param(blocks{j},'ObjectParameters');
 if isfield(parameters,'ContentPreviewEnabled'),set_param(blocks{j},'ContentPreviewEnabled','off');end
 try,set_param(blocks{j},'ForegroundColor','black','BackgroundColor','white');catch,end
 name=get_param(blocks{j},'Name');if startsWith(name,'RL '),set_param(blocks{j},'Name',['Diagnostic ' name(4:end)]);end
end
coil=[mdl '/Force controller/Coil PI and PID'];
set_param([coil '/Notched command plus modal damping'],'IconShape','rectangular');
set_param([coil '/Current saturation error'],'IconShape','rectangular');
root_layout(mdl);
set_param(mdl,'SimulationCommand','update');assert(isempty(Simulink.BlockDiagram.getAlgebraicLoops(mdl)));
assert(isequaln(originalVariables,workspace_variables(mw)),'Layout changed Model Workspace values.');
save_system(mdl,modelFile);

reference=load(fullfile(acceptanceFolder,'standalone_default_normal.mat'),'normalTime','normalTruth','default');
timer=tic;out=sim(mdl);firstWall=toc(timer);time=out.yout.get(2).Values.Time;truth=sample_rows(out.yout.get(2).Values,27);
assert(isequal(time,reference.normalTime));maximum=max(abs(truth-reference.normalTruth),[],'all');assert(maximum<1e-8);
save(fullfile(checkFolder,'final_versioned_default.mat'),'time','truth','-v7');clear out;Simulink.sdi.clear;
save_system(mdl,modelFile);close_system(mdl,0);load_system(modelFile);
timer=tic;out=sim(mdl);reopenWall=toc(timer);reopenTime=out.yout.get(2).Values.Time;reopenTruth=sample_rows(out.yout.get(2).Values,27);
assert(isequal(time,reopenTime)&&isequal(truth,reopenTruth));clear out;Simulink.sdi.clear;
set_param(mdl,'SimulationCommand','update');loops=numel(Simulink.BlockDiagram.getAlgebraicLoops(mdl));assert(loops==0);
save_system(mdl,modelFile);
report=struct('status','versioned_fixed_mechanics_native_model_delivery_accepted', ...
 'canonicalChanged',false,'qualificationEpisodes',0,'developmentOnly',true,'fullRequirementQualified',false, ...
 'modelFile',modelFile,'modelSha256',sha256(modelFile), ...
 'parentModelSha256',sha256(fullfile(acceptedFolder,[mdl '.slx'])), ...
 'parentAcceptanceFile',fullfile(acceptanceFolder,'acceptance.json'), ...
 'parentAcceptanceSha256',sha256(fullfile(acceptanceFolder,'acceptance.json')), ...
 'removedUnconnectedWireSegments',wireCount,'allConnectedEdgesPreserved',true,'allModelWorkspaceValuesPreserved',true, ...
 'scopeShowsWorkpieceNormalError',true,'scopeTruthUsedByController',false, ...
 'defaultFullTruthArrayMaximumDifference',maximum,'nativeSamples',numel(time), ...
 'saveReopenExact',true,'algebraicLoopCount',loops,'externalInputNeeded',false,'baselineHardSelected',true, ...
 'firstAcceleratorWall_s',firstWall,'reopenedWarmAcceleratorWall_s',reopenWall, ...
 'inheritedContactAndTravelStopAcceptance',true,'namespaceOnlyHelpers',true);
write_json(fullfile(checkFolder,'delivery_acceptance.json'),report);
write_json(fullfile(targetFolder,'delivery_acceptance.json'),report);
print(['-s' mdl],'-dpng',fullfile(checkFolder,'diagram_root.png'));
print(['-s' mdl '/Force controller/Coil PI and PID'],'-dpng',fullfile(checkFolder,'diagram_force_controller.png'));
print(['-s' mdl '/Contact force measurement/Head motion estimator'],'-dpng',fullfile(checkFolder,'diagram_upper_observer.png'));
copyfile([mfilename('fullpath') '.m'],fullfile(checkFolder,'publish_runnable_fixed_model_v8.m'));
fprintf('VERSIONED_RUNNABLE_MODEL_DELIVERED %s\n',jsonencode(report));
end
