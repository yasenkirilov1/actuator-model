function p=acf_prepare_cell_modal(p)
% Same selected modal equations with separately frozen identification inputs.
% Global force/mass calibration residuals may vary elsewhere in the controller.
% Actual sensor, driver or mechanical inputs must never redesign this filter.
assert(p.cellModal.enabled&&p.mechanics.k1==64e6&&p.mechanics.c1==0);
assert(isfield(p,'qualificationModalIdentification'));
o=p.cellModal;id=p.qualificationModalIdentification;dt=p.force.sampleTime;
mb=id.identifiedMassB_kg;k=id.identifiedStiffness_N_m;kf=id.identifiedForceConstant_N_A;
assert(mb==.6&&k==64e6&&kf==24.4&&id.identifiedCurrentResponse_s==50e-6);
assert(o.acquiredTransferReal==id.acquiredTransferReal&&o.acquiredTransferImag==id.acquiredTransferImag);
assert(o.identifiedCurrentResponse_s==id.identifiedCurrentResponse_s);
w=sqrt(k/mb);assert(abs(w/(2*pi)-o.carrier_Hz)<1e-9);
zeta=o.filterDamping;cv=o.virtualDamping_Ns_m;assert(zeta>0&&cv>0&&o.currentBound_A>0);
F=[0,w;-w,-2*zeta*w];G=[0;2*zeta*w];z=expm([F,G;zeros(1,3)]*dt);
A=z(1:2,1:2);B=z(1:2,3);carrier=exp(1i*w*dt);r=(carrier*eye(2)-A)\B;
bandpass=[0,1];properDerivative=[-1,-2*zeta];directDerivative=2*zeta;
h1=bandpass*r;h2=properDerivative*r+directDerivative;
acquired=o.acquiredTransferReal+1i*o.acquiredTransferImag;
current=1/(1+1i*w*id.identifiedCurrentResponse_s);
commandHold=exp(-1i*w*dt/2)*sin(w*dt/2)/(w*dt/2);
transmission=acquired*current*commandHold;
desired=-1i*w*cv/(k*transmission);
basis=[real(h1),real(h2);imag(h1),imag(h2)];assert(cond(basis)<100);
coeff=basis\[real(desired);imag(desired)];
C=(coeff(1)*bandpass+coeff(2)*properDerivative)/kf;D=coeff(2)*directDerivative/kf;
actualCarrier=(C*r+D)*kf*transmission;desiredCarrier=-1i*w*cv/k;
normalized=actualCarrier/desiredCarrier;dc=C*((eye(2)-A)\B)+D;
poles=eig(A);assert(max(abs(poles))<1&&all(isfinite([A(:);B(:);C(:);D(:)])));
assert(abs(normalized-1)<1e-12&&abs(dc)<1e-12);
p.d.cellModal=struct('A',A,'B',B,'C',C,'D',D,'initialState',zeros(2,1), ...
 'carrier_Hz',w/(2*pi),'filterDamping',zeta,'virtualDamping_Ns_m',cv, ...
 'basisBandpassTransferReal',real(h1),'basisBandpassTransferImag',imag(h1), ...
 'basisProperDerivativeTransferReal',real(h2),'basisProperDerivativeTransferImag',imag(h2), ...
 'basisCoefficientsForce',coeff,'basisCondition',cond(basis), ...
 'acquiredTransferReal',real(acquired),'acquiredTransferImag',imag(acquired), ...
 'commandToCoilForceTransferReal',real(current*commandHold), ...
 'commandToCoilForceTransferImag',imag(current*commandHold), ...
 'desiredActualForcePerTrueCellReal',real(desiredCarrier), ...
 'desiredActualForcePerTrueCellImag',imag(desiredCarrier), ...
 'normalizedPositiveDampingReal',real(normalized),'normalizedPositiveDampingImag',imag(normalized), ...
 'dcCurrentGain',dc,'maximumPoleMagnitude',max(abs(poles)), ...
 'currentBound_A',o.currentBound_A,'identifiedMassB_kg',mb,'identifiedStiffness_N_m',k, ...
 'identifiedForceConstant_N_A',kf,'stateNames',{{'normalized_resonant_integral_N','resonant_bandpass_N'}});
assert(isfield(id,'frozenPreparedCoefficients')&&isequaln(p.d.cellModal,id.frozenPreparedCoefficients), ...
 'Modal coefficients or diagnostics changed from the locked selected candidate.');
end
