function manifest=prepare_qualification_bank_v8(folder,selectionFile)
% Freeze one selected deterministic controller on736 unseen qualification cases.
% No physical simulations, candidate selection or qualification scoring here.
assert(~usejava('desktop'));maxNumCompThreads(2);
lock=jsondecode(fileread(selectionFile));assert(strcmp(lock.status,'locked_development_candidate_before_qualification'));
assert(lock.selectionOnly&&~lock.qualificationOutcomesInspected&&lock.noRetuningOnQualification);
assert(strcmp(sha256(lock.sourceConfigs.path),lock.sourceConfigs.sha256));
assert(strcmp(sha256(lock.contextRecipe.path),lock.contextRecipe.sha256));
names=fieldnames(lock.sourceFiles);
for j=1:numel(names),one=lock.sourceFiles.(names{j});assert(strcmp(sha256(one.path),one.sha256));end
for j=1:numel(lock.sourceHelpers),one=lock.sourceHelpers(j);assert(strcmp(sha256(one.path),one.sha256));end
for j=1:numel(lock.selectionEvidence),one=lock.selectionEvidence(j);assert(strcmp(sha256(one.path),one.sha256));end
recipe=jsondecode(fileread(lock.contextRecipe.path));assert(recipe.counts.total==736&&recipe.qualificationEpisodesExecuted==0);
loaded=load(lock.sourceConfigs.path,'configs');selected=loaded.configs(lock.selectedScenario+1);
assert(strcmp(selected.identity,lock.selectedIdentity)&&strcmp(selected.split,'development'));
base=selected.p;assert_fixed(base);
assert(base.mechanics.mA==1.5&&base.mechanics.mB==.6);
assert(base.upperObserver.identifiedMassA_kg==1.5&&base.upperObserver.identifiedStiffness_N_m==20000&&base.upperObserver.identifiedDamping_Ns_m==0);
assert(base.coil.forceConstant==24.4&&base.coil.resistance==8.896&&base.coil.inductance==.004&&base.coil.voltage==32);
assert(base.coil.currentResponse==50e-6&&base.adcStudy.identifiedAnalogCutoff_Hz==1900);
assert(base.sensor.distalMassCalibrationScale==1&&base.sensor.bias==0&&base.accel.bias==0&&base.accel.scaleError==0);
modal=base.d.cellModal;assert(modal.identifiedMassB_kg==.6&&modal.identifiedForceConstant_N_A==24.4&&modal.identifiedStiffness_N_m==64e6);
id=lock.frozenModalIdentification;id.frozenPreparedCoefficients=modal;
assert(id.acquiredTransferReal==base.cellModal.acquiredTransferReal&&id.acquiredTransferImag==base.cellModal.acquiredTransferImag);
assert(~isfolder(folder),'Preserve every prepared cohort.');mkdir(folder);
sourceHelpers=fullfile(lock.sourceNativeDirectory,'helpers');
copyfile(sourceHelpers,fullfile(folder,'selected_helper_snapshot'));
copyfile(sourceHelpers,fullfile(folder,'helpers'));
recipeFolder=fileparts(mfilename('fullpath'));
copyfile(fullfile(recipeFolder,'acf_prepare_cell_modal.m'),fullfile(folder,'helpers','acf_prepare_cell_modal.m'));
addpath(fullfile(folder,'helpers'),'-begin');
clear acf_prepare acf_adc_prepare acf_prepare_baseline_v8 acf_prepare_upper_observer acf_prepare_cell_modal acf_prepare_accel_lead;
base.qualificationModalIdentification=id;base.cellModal.identifiedCurrentResponse_s=id.identifiedCurrentResponse_s;
base=acf_prepare(base);assert(isequaln(base.d.cellModal,modal));
assert(isequaln(base.d,selected.p.d),'Nominal preparation adapter changes an existing prepared coefficient.');
controller=control_contract(base);configs=struct([]);metadata=struct([]);timer=tic;
for j=1:numel(recipe.cases)
 c=recipe.cases(j);p=base;
 p.mechanics.mA=1.5;p.mechanics.mB=.6;p.mechanics.mS=c.massS_kg;p.mechanics.angle=c.angle_rad;
 p.force.reference=c.force_N;p.contact.mu=c.mu;
 p.sim.stopTime=c.duration_s;p.sim.evaluateFrom=0;
 for name=fieldnames(c.surface)',p.surface.(name{1})=c.surface.(name{1});end
 p.robot.initialExcessForce=0;p.robot.initialPositionOffset_m=0;p.robot.errorForce=0;p.robot.nominalVelocity=0;
 p.robotPrediction.boundedNominalPath=true;
 p.sensor.distalMassCalibrationScale=1;
 for k=1:numel(c.overrides),p=set_value(p,c.overrides(k).path,c.overrides(k).value);end
 p.sensor.seed=c.seed;p.sensor.distalMass_kg=c.massS_kg;
 p.sensor.distalMass_model_kg=c.massS_kg*p.sensor.distalMassCalibrationScale;
 p.inertial.lowerLoadInverse.identifiedStiffness_N_m=64e6;
 p.inertial.lowerLoadInverse.identifiedDamping_Ns_m=0;
 p.inertial.lowerLoadInverse.identifiedMassB_kg=p.uncertainty.massB_model_kg;
 p.inertial.lowerLoadInverse.identifiedForceConstant_N_A=p.uncertainty.forceConstant_model_N_A;
 % The inherited source pair is diagnostic history; it is not a packing or
 % unseating requirement for the user's ideal upper spring.
 p.mechanicalStudy.design='qualification_fixed_upper20k_finite_cell_v8';
 p.mechanicalStudy.parentDesign=selected.p.mechanicalStudy.design;
 p.mechanicalStudy.selectedIdentity=lock.selectedIdentity;
 p.mechanicalStudy.qualificationCohort=c.cohort;p.mechanicalStudy.caseID=c.caseID;
 p.mechanicalStudy.upperLengthUnconstrained=true;
 p.mechanicalStudy.lowerExternalSpringPresent=false;p.mechanicalStudy.upperExternalSpringPresent=true;
 if isfield(p.mechanicalStudy,'externalUpperPair'),p.mechanicalStudy.externalUpperPair.lengthAndTravelUnconstrained=true;end
 p=acf_prepare(p);assert_fixed(p);
 assert(p.mechanics.mA==1.5&&p.upperObserver.identifiedMassA_kg==1.5);
 assert(p.upperObserver.identifiedStiffness_N_m==20000&&p.upperObserver.identifiedDamping_Ns_m==0);
 assert(isequaln(control_contract(p),controller),'Selected controller design changed.');
 assert(isequaln(p.d.cellModal,modal),'Selected modal coefficients changed.');
 assert(p.sim.step==1/300000&&p.adcStudy.fineClock_s==1/300000);
 assert(p.force.sampleTime==1e-4&&p.adcStudy.outputRate_Hz==30000&&p.robot.sampleTime==.01);
 assert(p.sensor.seed==c.seed&&p.sensor.distalMass_kg==c.massS_kg);
 assert(p.sensor.distalMass_model_kg==c.massS_kg*p.sensor.distalMassCalibrationScale);
 assert(p.inertial.lowerLoadInverse.identifiedMassB_kg==p.uncertainty.massB_model_kg);
 row=struct('p',p,'identity',c.identity,'split',c.split);
 if isempty(configs),configs=row;else,configs(end+1)=row;end
 m=case_metadata(p,c,lock);
 if isempty(metadata),metadata=m;else,metadata(end+1)=m;end
end
assert(numel(configs)==736&&numel(unique([metadata.seed]))==736);
assert(all([metadata.massA_kg]==1.5)&&all([metadata.identifiedMassA_kg]==1.5));
assert(sum(strcmp({configs.split},'qualification_nominal700'))==700);
assert(sum(strcmp({configs.split},'qualification_fresh32'))==32);
assert(sum(strcmp({configs.split},'qualification_long4'))==4);
% Preparation-only intervention guards. These do not run a plant or score a
% physical episode. All modal inputs remain identified frozen quantities.
interventions=struct([]);
for j=1:3
 altered=base;
 if j==1,altered.coil.currentResponse=2*base.coil.currentResponse;label='actual_current_response_doubled';
 elseif j==2,altered.adcStudy.analogCutoff_Hz=.95*base.adcStudy.analogCutoff_Hz;label='actual_common_response_minus5pct';
 else,altered.uncertainty.massB_model_kg=.6015;altered.inertial.lowerLoadInverse.identifiedMassB_kg=.6015;altered.uncertainty.forceConstant_model_N_A=24.461;altered.inertial.lowerLoadInverse.identifiedForceConstant_N_A=24.461;label='global_identified_holder_and_Kf_residual';end
 altered=acf_prepare(altered);exact=isequaln(altered.d.cellModal,modal);assert(exact);
 r=struct('label',label,'fullModalPreparedCoefficientsExact',exact,'physicalEpisodesExecuted',0);
 if isempty(interventions),interventions=r;else,interventions(end+1)=r;end
end
save(fullfile(folder,'configs.mat'),'configs','-v7');
copyfile(selectionFile,fullfile(folder,'candidate_lock.json'));
copyfile(lock.contextRecipe.path,fullfile(folder,'context_recipe.json'));
save(fullfile(folder,'coefficient_guard.mat'),'controller','modal','id','interventions','-v7');
helpers=helper_hashes(fullfile(folder,'helpers'));
manifest=struct('status','qualification_parameters_frozen_not_executed','date','2026-10-05', ...
 'cases',metadata,'qualificationCases',736,'cohortCounts',recipe.counts, ...
 'sourceModelSha256',lock.sourceModelSha256,'sourceNativeModel',lock.sourceNativeModel, ...
 'configsSha256',sha256(fullfile(folder,'configs.mat')),'selectedSourceConfigsSha256',lock.sourceConfigs.sha256, ...
 'selectedSourceScenario',lock.selectedScenario,'selectedSourceIdentity',lock.selectedIdentity, ...
 'candidateLockSha256',sha256(selectionFile),'contextRecipeSha256',lock.contextRecipe.sha256, ...
 'preparationWall_s',toc(timer),'helpers',helpers,'modalIdentification',id, ...
 'controllerDesign',controller,'preparationInterventions',interventions, ...
 'allPreparedModalCoefficientsExactlySelected',true,'selectedNominalPreparedCoefficientsExact',true, ...
 'actualMassA_kg',1.5,'identifiedMassA_kg',1.5,'upperLengthAndTravelUnconstrained',true, ...
 'qualificationEpisodesExecuted',0,'sourceOrSineGuardsAreQualification',false, ...
 'scenarioRangesInclusive',recipe.scenarioRangesInclusive, ...
 'seedContract',recipe.seedContract,'translationContract',recipe.translationContract, ...
 'qualificationContract',recipe.qualificationContract);
write_json(fullfile(folder,'manifest.json'),manifest);
copyfile([mfilename('fullpath') '.m'],fullfile(folder,'prepare_qualification_bank_v8.m'));
fprintf('QUALIFICATION_V8_PARAMETERS_FROZEN %d cases,noepisodes,%.3fs\n',numel(configs),manifest.preparationWall_s);
end

function assert_fixed(p)
assert(~p.mechanics.upperRigid&&p.mechanics.k2==20000&&p.mechanics.c2==0);
assert(~p.mechanics.lowerRigid&&p.mechanics.k1==64e6&&p.mechanics.c1==0);
assert(~p.inertial.lowerLoadInverse.enabled&&~isfield(p,'springs'));
end

function c=control_contract(p)
% Design choices stay frozen. Known-tool scaling, identified calibration and
% loaded initial values are allowed to change through the same equations.
c=struct('upperObserver',p.upperObserver,'cellModal',p.cellModal, ...
 'modalIdentification',p.qualificationModalIdentification, ...
 'inertialExceptLowerInverse',rmfield(p.inertial,'lowerLoadInverse'), ...
 'forceSettingsExceptReference',rmfield(p.force,'reference'), ...
 'coil',p.coil,'robotForceGate',p.robot.forceGate, ...
 'robotRecenterGain',p.robot.recenterGain,'robotDeadband',p.robot.deadband, ...
 'robotSampleTime',p.robot.sampleTime,'sensorForceNoiseRms_N',p.sensor.noiseRms, ...
 'sensorPositionNoiseRms_m',p.sensor.strokeNoiseRms,'accelerationNoiseRms_m_s2',p.accel.noiseRms, ...
 'accelerationRange_g',p.accel.range_g, ...
 'identifiedAnalogCutoff_Hz',p.adcStudy.identifiedAnalogCutoff_Hz, ...
 'identifiedEmaTime_s',p.adcStudy.identifiedEmaTime_s, ...
 'identifiedPipelineDelay_s',p.adcStudy.identifiedPipelineDelay_s, ...
 'identifiedAcquisition',struct('antiAliasCutoff_Hz',p.acquisition.identifiedAntiAliasCutoff_Hz, ...
 'emaTime_s',p.acquisition.identifiedEmaTime_s,'pipelineDelay_s',p.acquisition.identifiedPipelineDelay_s));
for field={'accelLead','cellModalLead','guideFeedforwardStudy'}
 if isfield(p,field{1}),c.(field{1})=p.(field{1});end
end
end

