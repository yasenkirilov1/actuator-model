end

function p=set_value(p,path,value)
parts=strsplit(path,'.');assert(numel(parts)==2&&isfield(p,parts{1})&&isfield(p.(parts{1}),parts{2}));
p.(parts{1}).(parts{2})=value;
end

function hashes=helper_hashes(folder)
files=dir(fullfile(folder,'*.m'));hashes=struct([]);
for j=1:numel(files)
 one=struct('name',files(j).name,'sha256',sha256(fullfile(folder,files(j).name)));
 if isempty(hashes),hashes=one;else,hashes(end+1)=one;end
end
end

function h=sha256(file)
fid=fopen(file,'rb');assert(fid>=0);clean=onCleanup(@()fclose(fid));d=java.security.MessageDigest.getInstance('SHA-256'); %#ok<NASGU>
while ~feof(fid),b=fread(fid,1024*1024,'*uint8');d.update(typecast(b,'int8'));end
h=lower(reshape(dec2hex(typecast(d.digest(),'uint8'),2)',1,[]));
end

function write_json(file,value)
fid=fopen(file,'w');assert(fid>=0);fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));fclose(fid);
end
