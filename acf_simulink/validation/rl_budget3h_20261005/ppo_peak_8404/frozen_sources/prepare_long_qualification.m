function manifest=prepare_long_qualification(folder)
% Freeze four new30s histories; preparation is not executed qualification.
assert(~usejava('desktop'));maxNumCompThreads(2);
root=fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
parent=fullfile(root,'acf_simulink','validation','rl_budget3h_20261005');
if nargin<1,folder=fullfile(parent,'long_qualification_bank');end
assert(~isfolder(folder),'Preserve frozen qualifications.');mkdir(folder);
source=fullfile(root,'acf_simulink','validation','adc_acquisition_trial_20261002');
copyfile(fullfile(source,'helpers'),fullfile(folder,'helpers'));addpath(fullfile(folder,'helpers'),'-begin');clear acf_prepare acf_adc_prepare acf_prepare_baseline_v8;
hotFile=fullfile(root,'acf_simulink','validation','budget_adc_hot_coil_20261002_inputs','ADXL1002_8000_M08_30k_current100_hot32V_configs.mat');hot=load(hotFile,'configs');
indices=[1 2 5 4];offsets=[0 .002 0 -.002];drifts=[0 .005 0 -.005];configs=struct([]);metadata=struct([]);sources=struct([]);
for k=1:4
 original=hot.configs(indices(k));p=original.p;
 p.sensor.seed=980000+k;p.sim.stopTime=30;p.sim.evaluateFrom=0;
 p.surface.kind='repeated';p.surface.startTime=1.3+.113*k;p.surface.repeatPeriod=1.2+.037*k;
 p.surface.height=.001;p.surface.width=.01;p.surface.scanSpeed=.1;
 p.robot.initialExcessForce=0;p.robot.initialPositionOffset_m=offsets(k);p.robot.nominalVelocity=drifts(k);p.robot.errorForce=0;
 p.robotPrediction.boundedNominalPath=false;p=acf_prepare(p);
 assert(abs(p.coil.currentResponse-100e-6)<1e-15&&p.coil.voltage==32&&p.coil.forceConstant==24.4&&p.coil.resistance==8.896);
 assert(p.sim.step==1/300000&&p.force.sampleTime==1e-4);
 initialTravel=p.mechanics.midTravel+p.d.u0;assert(initialTravel>p.mechanics.travelMin&&initialTravel<p.mechanics.travelMax);
 identity=sprintf('qualification_long_%02d',k);c=struct('p',p,'identity',identity,'split','qualification');
 if isempty(configs),configs=c;else,configs(end+1)=c;end
 r=struct('scenario',k-1,'identity',identity,'split','qualification','curriculum','long_fresh_qualification', ...
 'massS_kg',p.mechanics.mS,'identifiedMassS_kg',p.sensor.distalMass_model_kg, ...
 'massB_kg',p.mechanics.mB,'identifiedMassB_kg',p.uncertainty.massB_model_kg,'massA_kg',p.mechanics.mA, ...
 'force_N',p.force.reference,'angle_rad',p.mechanics.angle,'mu_hidden',p.contact.mu,'seed',p.sensor.seed, ...
 'offset_m',p.robot.initialPositionOffset_m,'duration_s',p.sim.stopTime,'bumpStart_s',p.surface.startTime, ...
 'bumpHeight_m',p.surface.height,'bumpKind',p.surface.kind,'repeatPeriod_s',p.surface.repeatPeriod, ...
 'bumpWidth_m',p.surface.width,'scanSpeed_m_s',p.surface.scanSpeed,'actualK_N_m',p.mechanics.k1,'actualC_N_s_m',p.mechanics.c1, ...
 'identifiedKf_N_A',p.uncertainty.forceConstant_model_N_A, ...
 'identifiedK_N_m',p.inertial.lowerLoadInverse.identifiedStiffness_N_m,'identifiedC_N_s_m',p.inertial.lowerLoadInverse.identifiedDamping_Ns_m, ...
 'coilR_ohm',p.coil.resistance,'coilL_H',p.coil.inductance,'usableVoltage_V',p.coil.voltage,'peakCurrent_A',p.coil.peakCurrent, ...
 'midTravel_m',p.mechanics.midTravel,'travelMin_m',p.mechanics.travelMin,'travelMax_m',p.mechanics.travelMax, ...
 'knownEquilibriumCurrent_A',(p.force.reference-(p.uncertainty.massB_model_kg+p.sensor.distalMass_model_kg)*p.d.g)/p.uncertainty.forceConstant_model_N_A, ...
 'knownNominalRobotVelocity_m_s',p.robot.nominalVelocity,'boundedNominalPath',false,'initialActualTravel_m',initialTravel, ...
 'acceptedRecenterBand_m',.0075,'robotActionScale_m_s',.01);
 if isempty(metadata),metadata=r;else,metadata(end+1)=r;end
 s=struct('scenario',k-1,'sourceHotConfigurationIndex',indices(k),'sourceRetainedParameterIndex',original.retainedParameterIndex, ...
 'sourceRetainedParameterSha256',original.retainedParameterSha256,'sourceRetainedParameterSource',original.retainedParameterSource, ...
 'staticJointCorner',p.uncertainty.jointCorner,'knownMixedMechanics',k==3);
 if isempty(sources),sources=s;else,sources(end+1)=s;end
end
save(fullfile(folder,'configs.mat'),'configs','-v7');
manifest=struct('status','prepared_frozen_not_executed','cases',metadata,'sourceContexts',sources,'qualificationCases',4, ...
 'sourceModelSha256',sha256(fullfile(source,'acf_force_control_adc_trial.slx')),'hotInputsSha256',sha256(hotFile), ...
 'configsSha256',sha256(fullfile(folder,'configs.mat')), ...
 'contract','Fourfresh30s qualificationhistories,newseeds980001–4,realhot24.4N/A8.896ohm4mH/32V100uscurrenttarget,allnativephysics/acquisitionpreserved. Repeated1mm10mm100mm/sbumps;two sustained±5mm/srobotprograms fromt0,unboundedcommandpredictor,existinggate/sign/gain/queue/limits. Fourretainedcalibratedconfigurations,NOTfourindependentstaticerrorcorners. Thirdusesretainedexactlyidentified+20%k/−20%c mixedmechanics. No actorpreview orhiddenbumpclock. No contexts/outcomesbeforewinnerlock.');
write_json(fullfile(folder,'manifest.json'),manifest);copyfile([mfilename('fullpath') '.m'],fullfile(folder,'prepare_long_qualification.m'));
fprintf('RL_LONG_QUALIFICATION_FROZEN 4cases,0executed\n');
end
function s=sha256(file)
fid=fopen(file,'r');assert(fid>=0);bytes=fread(fid,Inf,'*uint8');fclose(fid);digest=java.security.MessageDigest.getInstance('SHA-256');digest.update(bytes);
s=lower(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end
function write_json(file,value)
fid=fopen(file,'w');assert(fid>=0);fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));fclose(fid);
end
