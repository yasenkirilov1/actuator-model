function place(mdl,positions)
for j=1:size(positions,1),set_param([mdl '/' positions{j,1}],'Position',positions{j,2});end
end
function replace_input(mdl,destination,index,name,tag,position)
ports=get_param([mdl '/' destination],'PortHandles');line=get_param(ports.Inport(index),'Line');src=get_param(line,'SrcPortHandle');
delete_line(mdl,src,ports.Inport(index));
add_block('simulink/Signal Routing/From',[mdl '/' name],'GotoTag',tag,'Position',position);
from=get_param([mdl '/' name],'PortHandles');add_line(mdl,from.Outport(1),ports.Inport(index),'autorouting','on');
end
function note(mdl,text,position)
a=Simulink.Annotation(mdl,text);a.Position=position;a.FontSize=12;
end
