function contract=install_accel_lead(mdl,p)
% Native proper filter on current feedforward only; no measurement retiming.
assert(p.accelLead.enabled&&p.inertial.accelerationPrediction_s==0);
sys=[mdl '/Force controller/Coil PI and PID/Measured motion feedforward'];
source=[sys '/Causal acceleration for current FF'];target=[sys '/Measured acceleration current feedforward'];
ph=get_param(target,'PortHandles');line=get_param(ph.Inport(1),'Line');
assert(line~=-1&&strcmp(get_param(get_param(line,'SrcBlockHandle'),'Name'),'Causal acceleration for current FF'));
delete_line(sys,'Causal acceleration for current FF/1','Measured acceleration current feedforward/1');
add_block('simulink/Discrete/Discrete Transfer Fcn',[sys '/Present-time acceleration lead for current FF'], ...
 'Numerator','p.d.accelLead.numerator','Denominator','p.d.accelLead.denominator', ...
 'SampleTime','p.force.sampleTime','InitialStates','0','Position',[1055 195 1325 245]);
add_line(sys,'Causal acceleration for current FF/1','Present-time acceleration lead for current FF/1','autorouting','on');
add_line(sys,'Present-time acceleration lead for current FF/1','Measured acceleration current feedforward/1','autorouting','on');
contract=struct('enabled',true,'causal',true,'input','Matched-frame measured S acceleration', ...
 'outputUse','Current force feedforward ONLY', ...
 'measurementFrameUnchanged',true,'surfacePreview',false,'robotFutureInputs',false, ...
 'formula','(1+(tauPole+tauAdvance)*s)/(1+tauPole*s)', ...
 'discretization','Bilinear at fresh 10 kHz force frame','initialState',0, ...
 'poleTime_s',p.accelLead.poleTime_s,'advanceTime_s',p.accelLead.advanceTime_s, ...
 'discreteNumerator',p.d.accelLead.numerator,'discreteDenominator',p.d.accelLead.denominator, ...
 'highFrequencyGain',p.d.accelLead.highFrequencyGain,'sampleTime_s',p.force.sampleTime);
end
